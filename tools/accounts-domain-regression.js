#!/usr/bin/env node
"use strict";
const assert = require("assert");
const { toPaise, fromPaise, validateOpeningInvoice, validateCollection, buildCollectionJournal, assertBalanced } = require("../backend/modules/accounts/accounts.domain");
assert.strictEqual(toPaise("125.50"), 12550);
assert.strictEqual(fromPaise(12550), 125.5);
assert.throws(() => toPaise(-1), /non-negative/);
assert.throws(() => toPaise("NaN"), /non-negative/);
const opening = validateOpeningInvoice({ customerCode: "C001", invoiceNo: "OLD-104", invoiceDate: "2025-03-01", originalAmount: "1500.00", outstandingAmount: "900.00", evidencePath: "accounts/opening/C001-OLD-104.jpg" });
assert.strictEqual(opening.sourceKind, "opening");
assert.strictEqual(opening.originalAmount, 1500);
assert.strictEqual(opening.openingOutstanding, 900);
assert.throws(() => validateOpeningInvoice({ customerCode: "C001", invoiceNo: "OLD-105", invoiceDate: "2025-03-01", originalAmount: 100, outstandingAmount: 101, evidencePath: "accounts/bill.jpg" }), /cannot exceed/);
assert.throws(() => validateOpeningInvoice({ customerCode: "C001", invoiceNo: "OLD-106", invoiceDate: "2025-03-01", originalAmount: 100, outstandingAmount: 50 }), /evidence/);
const balances = { "inv-1": { customerCode: "C001", outstandingAmount: 500 }, "inv-2": { customerCode: "C001", outstandingAmount: 300 }, "inv-3": { customerCode: "C002", outstandingAmount: 100 } };
const collection = validateCollection({ customerCode: "C001", method: "cash", total: 650, requestKey: "req-1", allocations: [{ invoiceId: "inv-1", amount: 500, evidencePath: "accounts/bills/inv-1.jpg" }, { invoiceId: "inv-2", amount: 150, evidencePath: "accounts/bills/inv-2.jpg" }] }, balances);
assert.strictEqual(collection.total, 650);
assert.strictEqual(collection.allocations.length, 2);
assertBalanced(buildCollectionJournal(collection));
assert.throws(() => validateCollection({ customerCode: "C001", method: "cash", allocations: [{ invoiceId: "inv-1", amount: 501, evidencePath: "accounts/bills/1.jpg" }] }, balances), /exceed/);
assert.throws(() => validateCollection({ customerCode: "C001", method: "cash", allocations: [{ invoiceId: "inv-3", amount: 50, evidencePath: "accounts/bills/3.jpg" }] }, balances), /does not belong/);
assert.throws(() => validateCollection({ customerCode: "C001", method: "upi", allocations: [{ invoiceId: "inv-1", amount: 10 }] }, balances), /evidence/);
assert.throws(() => validateCollection({ customerCode: "C001", method: "cash", allocations: [{ invoiceId: "inv-1", amount: 10, evidencePath: "accounts/bills/1.jpg" }] }, balances), /request reference/);
assert.throws(() => assertBalanced([{ accountCode: "CASH", debit: 100, credit: 0 }, { accountCode: "AR", debit: 0, credit: 99 }]), /not balanced/);
assert.throws(() => assertBalanced([{ accountCode: "INVALID", debit: 100, credit: 100 }, { accountCode: "AR", debit: 0, credit: 0 }]), /either a debit or a credit/);
// Static schema-contract checks (SQL execution requires a disposable PostgreSQL/Supabase project).
const fs = require("fs");
const sql = fs.readFileSync(require("path").join(__dirname, "../sql/supabase-accounts-phase-1.sql"), "utf8");
assert(sql.includes("gm_accounts_create_opening_invoice"));
assert(sql.includes("OPENING_BALANCE_EQUITY"));
assert(sql.includes("gm_accounts_record_collection"));
assert(sql.includes("COLLECTION_SUSPENSE"));
assert(sql.includes("gm_accounts_approve_collection"));
assert(sql.includes("for update"));
assert(sql.includes("unique"));
assert(sql.includes("enable row level security"));
assert(sql.includes("Every allocation needs a positive amount and bill-photo evidence"));
assert(sql.includes("status='approved'"));
console.log("Accounts domain regression: 24 assertions passed (14 domain + 10 schema-contract).");
